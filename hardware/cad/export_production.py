        "| 1 | Seeed XIAO ESP32-S3 Sense | with its camera, heatsink and FPC antenna |",
        "| 2 | MG90S micro servo — Waveshare 15024 (pishop.us / waveshare.com), or Adafruit SG92R (169) | D0 = pan, D1 = tilt; body 22.8 × 12.2 (stated). Clones vary: check one against the test prints |",
        "| 1 | LiPo 3.7 V 150 mAh — Adafruit 1317 (19.75 × 26.02 × 3.8, JST-PH) | optional backup; cut the JST and solder to the XIAO BAT pads |",
