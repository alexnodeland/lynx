        "| 1 | 470 µF 6.3 V electrolytic — Panasonic EEU-FR0J471 (6.3 × 11.2) | across servo 5 V / GND, inside the power pod |",
        "| 1 | microSD card | optional |", "",
        "## Hardware", "",
        "| Qty | Part | Where |", "|---|---|---|",
        "| 9 | M2 × 8 thread-forming for plastic, pan head — e.g. McMaster 99461A916 | the only screw: lid (2), shroud (2), pan-servo tabs (2), pan cap sides (2), tilt pivot (1) |",
        "| 2 | M3 / #4 countersunk wood screws (optional) | wall-mounting the base; the magnet is the alternative |",
        "| 1 | K&J Magnetics D82, 12.7 × 3.17 mm N42 disc (2.9 kg pull) | pressed into the base underside |",
        "| 1 | compression spring, ~6 mm OD, 10 mm, 0.5 mm wire (McMaster spring finder) | strain relief where the internal cable leaves the pod |",
        "| 1 | 1/4 in PET braided sleeve, ~30 cm — Kable Kontrol FW025 | over the internal USB-C cable |",
        "| 6 | 304 stainless woven mesh ~20 × 20 (McMaster), cut to the `VentMesh` pieces | behind the vent slots (glue) |",
