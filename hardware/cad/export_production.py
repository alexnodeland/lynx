"""Export the lynx production package (run in FreeCAD after build_revD.py, with its globals):

    exec(open(".../export_production.py").read(), g)

Writes production/: one print-oriented STL + STEP per printed part, test-print STLs,
lynx-assembly.step (everything, assembled), and BOM.md with lengths measured from the model.
"""
import os

import FreeCAD as App
import Import
import MeshPart

G = globals()
V = App.Vector
doc = App.getDocument("Combined")
OUTD = os.path.join(G["HERE"], "production")
os.makedirs(OUTD, exist_ok=True)


def flip_x(s):
    s.rotate(s.BoundBox.Center, V(1, 0, 0), 180)
    return s


def x_up(s):        # stand the part on its -X face (+X end up)
    s.rotate(s.BoundBox.Center, V(0, 1, 0), -90)
    return s


# part: (orientation fn, print note)
PRINTED = {
    "Base": (flip_x, "Open side down (floor and cheeks up). Supports: off. The floor bridges the cavity."),
    "Lid": (flip_x, "Top face down. Supports: on, touching the build plate only, under the lens-bezel step."),
    "BatteryTray": (None, "Plate down, posts up. Supports: off."),
    "Yoke": (None, "Plate down, uprights up. Supports: off. 4 walls / 40 % infill: it carries the camera."),
    "PanBase": (None, "Flange down. Supports: off."),
    "PanCap": (flip_x, "Open side down (collar up). Supports: off."),
    "ServoShroud": (x_up, "Open end down, fins up. Supports: off."),
    "LightPipePrint": (None, "As modelled (arm on the bed, riser up). Clear PETG, 100 % infill, 0.12 mm layers."),
}
TEST = ("FitCoupon_USBEnd", "FitCoupon_Boss", "FitCoupon_LidCorner")
rows = []
for name, (orient, note) in PRINTED.items():
    shp = doc.getObject(name).Shape.copy()
    if orient:
        shp = orient(shp)
    shp.translate(V(0, 0, -shp.BoundBox.ZMin))
    fname = "lynx-" + name.lower().replace("print", "")
    mesh = MeshPart.meshFromShape(Shape=shp, LinearDeflection=0.01, AngularDeflection=0.1)
    mesh.write(os.path.join(OUTD, fname + ".stl"))
    tmp = doc.addObject("Part::Feature", "tmp_" + name)
    tmp.Shape = doc.getObject(name).Shape
    Import.export([tmp], os.path.join(OUTD, fname + ".step"))
    doc.removeObject(tmp.Name)
    bb = shp.BoundBox
    rows.append((fname, f"{bb.XLength:.1f} x {bb.YLength:.1f} x {bb.ZLength:.1f}", f"{shp.Volume / 1000:.2f}", note,
                 mesh.isSolid()))
for name in TEST:
    shp = flip_x(doc.getObject(name).Shape.copy()) if name != "FitCoupon_LidCorner" else doc.getObject(name).Shape.copy()
    shp.translate(V(0, 0, -shp.BoundBox.ZMin))
    MeshPart.meshFromShape(Shape=shp, LinearDeflection=0.01, AngularDeflection=0.1).write(
        os.path.join(OUTD, "test-" + name.replace("FitCoupon_", "").lower() + ".stl"))
asm = [o for o in doc.Objects if o.TypeId in ("PartDesign::Body", "Part::Feature") and o.Visibility
       and not o.Name.startswith(("FitCoupon", "tmp_"))]
Import.export(asm, os.path.join(OUTD, "lynx-assembly.step"))

# screw lengths from the geometry
cap_screw = 8.0
shroud_screw = G["SH_WALL"] + G["SG_TAB_T"] + (G["RX1"] - G["RX0"]) + 0.5
std = lambda L: min((x for x in (4, 5, 6, 8, 10, 12, 14, 16, 18, 20, 25) if x >= L - 0.6), default=25)
bad = [f for f, *_r, ok in rows if not ok]
if bad:                                      # production gate: a slicer must never get a leaky mesh
    raise RuntimeError(f"non-watertight STL(s): {bad} — fix the model before exporting")
REPORT_PROD = {"rows": rows, "cap_screw": (cap_screw, std(cap_screw)), "shroud_screw": (shroud_screw, std(shroud_screw))}

